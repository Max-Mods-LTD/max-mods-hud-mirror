'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const link = require('../tools/oap_link.js');
const donor = require('./synthetic_donor.js');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'build', 'package-test');
fs.mkdirSync(out, { recursive: true });
const manifest = link.readManifest(path.join(root, 'car'));
const fake = path.join(out, 'synthetic-donor.tgz');
donor.tgz(fake, { main: 'javascript/entry.js' });
const built = path.join(out, manifest.id + '@' + manifest.version + '.tgz');
const result = link.build(path.join(root, 'car'), built, { donors: [fake] });
assert(result.moduleCount >= manifest.modules.length);
const files = link.untar(fs.readFileSync(built));
const names = files.map((f) => f.name);
assert(names.some((n) => n.endsWith('javascript/app.js')));
manifest.modules.forEach((m) => cp.execFileSync(process.execPath, ['--check', path.join(root, 'car', m)]));
const src = path.join(root, 'dist', manifest.id + '@' + manifest.version + '.src.tgz');
link.packSource(path.join(root, 'car'), src);
const source = link.untar(fs.readFileSync(src));
assert(!source.map((f) => f.name).some((n) => /node_modules\/oap-sdk|\.p12$|\.keystore$|javascript\/app\.js$/.test(n)));
const repo = JSON.parse(fs.readFileSync(path.join(root, 'mgu-repo.json')));
assert.strictEqual(repo.components[0].path, 'car');
assert.deepStrictEqual(repo.components[0].mguHmi, ['ID7']);
assert(repo.components[0].requires['cluster-render']);
const permissions = JSON.parse(fs.readFileSync(path.join(root, 'car', manifest.tree, 'manifest.json')));
const readOnly = ['de.bmw.infotainment.vehicle.Vehicle2','de.bmw.infrastructure.VehicleInformation'];
readOnly.forEach((i) => Object.values(permissions.proxies[i].attributes).forEach((f) => assert.strictEqual(f, 'rs')));
console.log('PASS Store package, module linking against made-up SDK stubs, Node syntax, source-only distribution and read-only vehicle declarations');
console.log('This is not an MGU emulator or hardware test. The fake donor is never distributed.');
